/// Generate a fake file with appropriate content and MIME type for a given extension.
/// Returns None if the extension is not recognized.
pub fn fake_file_for_extension(ext: &str) -> Option<(Vec<u8>, String)> {
    if ext == "eml" {
        return Some((
            fake_eml_body(crate::faketime::fake_now()).into_bytes(),
            "message/rfc822".to_string(),
        ));
    }

    FAKE_FILES
        .iter()
        .find(|(e, _, _)| *e == ext)
        .map(|(_, content, mime)| (content.to_vec(), (*mime).to_string()))
}

fn fake_eml_body(now: chrono::DateTime<chrono::Utc>) -> String {
    format!(
        "From: user@example.com\r\nTo: admin@example.com\r\nSubject: Test\r\nDate: {}\r\n\r\nTest email.\r\n",
        now.format("%a, %-d %b %Y %H:%M:%S +0000")
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fake_eml_body_uses_supplied_utc_time() {
        let now = chrono::DateTime::from_timestamp(1_704_067_200, 0).expect("valid instant");

        assert!(fake_eml_body(now).contains("Date: Mon, 1 Jan 2024 00:00:00 +0000\r\n"));
    }

    #[test]
    fn fake_eml_lookup_does_not_use_frozen_placeholder_date() {
        let (body, mime) = fake_file_for_extension("eml").expect("eml fake file");
        let body = String::from_utf8(body).expect("eml body should be UTF-8");

        assert_eq!(mime, "message/rfc822");
        assert!(body.contains("\r\nDate: "));
        assert!(!body.contains("Date: Mon, 1 Jan 2024 00:00:00 +0000"));
    }

    #[test]
    fn fake_eml_lookup_uses_faketime_offset() {
        let baseline = crate::faketime::get_delta();
        crate::faketime::set_delta(86_400);

        let (body, mime) = fake_file_for_extension("eml").expect("eml fake file");
        let body = String::from_utf8(body).expect("eml body should be UTF-8");
        let expected = fake_eml_body(crate::faketime::fake_now());

        assert_eq!(mime, "message/rfc822");
        assert_eq!(body, expected);

        crate::faketime::set_delta(baseline);
    }
}
